-- Agent demo: a leave assistant (flow leave_agent_demo) with three ways of using an agent:
--   1. Apply for leave       : the agent gathers the request; the flow's Summary and Submit save it
--   2. Let the assistant book: the agent writes itself with the book_leave tool (the user confirms first)
--   3. My leave and requests : the agent answers questions with read-only tools
-- Needs upgrade_phase_f.sql (FC_AI_* tables) and an AI provider registered as CORP_LLM:
--   insert into fc_ai_providers (provider_id, base_url, model, credential_id, tool_mode)
--   values ('corp_llm', 'https://<host>/v1', '<model>', '<web credential static id or null>', 'native');
-- Run as the parsing schema:  sql user/pass@db @16_seed_agent_demo.sql      Safe to re-run.
