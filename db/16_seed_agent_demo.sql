create or replace package fc_demo_leave authid definer as
  -- Every function receives the FlowChat connector payload. The user is always payload.appUser,
  -- which FC_ENGINE fills from the APEX session: the model cannot choose whose leave it sees.
  function get_balance   (p_payload in clob) return clob;   -- tool get_leave_balance
  function list_requests (p_payload in clob) return clob;   -- tool list_my_leave
  function book_leave    (p_payload in clob) return clob;   -- tool book_leave (write; args leave_type, start_date, days, reason)
  function submit_leave  (p_payload in clob) return clob;   -- Submit node (slots leave_type, start_date, days, reason)
end fc_demo_leave;
/

create or replace package body fc_demo_leave as

  function user_of (p in json_object_t) return varchar2 is
  begin
    return upper(nvl(p.get_string('appUser'), user));
  end user_of;

  -- Every user gets demo entitlements the first time.
  procedure ensure_user (p_user in varchar2) is
  begin
    insert into fc_demo_leave_balances (app_user, leave_type, entitled)
    select p_user, t.leave_type, t.entitled
      from (select 'annual' leave_type, 15 entitled from dual union all
            select 'sick', 8 from dual union all
            select 'unpaid', 30 from dual) t
     where not exists (select 1 from fc_demo_leave_balances b where b.app_user = p_user and b.leave_type = t.leave_type);
  end ensure_user;

  function remaining (p_user in varchar2, p_type in varchar2) return number is
    l_n number;
  begin
    select b.entitled - nvl((select sum(q.days) from fc_demo_leave_requests q
                              where q.app_user = b.app_user and q.leave_type = b.leave_type
                                and q.status in ('SUBMITTED', 'BOOKED')
                                and extract(year from q.start_date) = extract(year from sysdate)), 0)
      into l_n
      from fc_demo_leave_balances b
     where b.app_user = p_user and b.leave_type = p_type;
    return l_n;
  exception when no_data_found then
    return 0;
  end remaining;

  function num_of (p in json_object_t, p_key in varchar2) return number is
  begin
    if p is null or not p.has(p_key) or p.get(p_key).is_null then return null; end if;
    if p.get(p_key).is_number then return p.get_number(p_key); end if;
    return to_number(p.get_string(p_key), '999999D99', 'NLS_NUMERIC_CHARACTERS=''.,''');
  exception when others then
    return null;
  end num_of;

  function str_of (p in json_object_t, p_key in varchar2) return varchar2 is
  begin
    if p is null or not p.has(p_key) or p.get(p_key).is_null then return null; end if;
    if p.get(p_key).is_string then return p.get_string(p_key); end if;
    return p.get(p_key).to_string;
  end str_of;

  -- Checks a request against the demo policy and inserts it. Returns an error message, or null and p_ref.
  function create_request (p_user in varchar2, p_type in varchar2, p_start in varchar2, p_days in number,
                           p_reason in varchar2, p_status in varchar2, p_ref out varchar2) return varchar2 is
    l_date date;
    l_left number;
    l_id   number;
  begin
    if p_type is null or p_type not in ('annual', 'sick', 'unpaid') then
      return 'Unknown leave type "' || p_type || '". Use annual, sick or unpaid.';
    end if;
    begin
      l_date := to_date(substr(p_start, 1, 10), 'YYYY-MM-DD');
    exception when others then
      return 'The first day must be a date (YYYY-MM-DD).';
    end;
    if p_days is null or p_days < 0.5 or p_days > 30 or mod(p_days * 2, 1) <> 0 then
      return 'Days must be between 0.5 and 30, in half days.';
    end if;
    if p_type = 'annual' and l_date < trunc(sysdate) + 14 then
      return 'Annual leave must start at least 14 days from today (on or after ' || to_char(trunc(sysdate) + 14, 'YYYY-MM-DD') || ').';
    end if;
    if p_type = 'annual' and p_days > 15 then
      return 'Annual leave is at most 15 consecutive working days.';
    end if;
    if p_type = 'sick' and (l_date > trunc(sysdate) or l_date < trunc(sysdate) - 7) then
      return 'Sick leave can start today or up to 7 days ago.';
    end if;
    if p_type = 'unpaid' and trim(p_reason) is null then
      return 'Unpaid leave needs a reason.';
    end if;
    ensure_user(p_user);
    l_left := remaining(p_user, p_type);
    if p_days > l_left then
      return 'Only ' || l_left || ' ' || p_type || ' days are left this year.';
    end if;
    insert into fc_demo_leave_requests (app_user, leave_type, start_date, days, reason, status)
    values (p_user, p_type, l_date, p_days, substr(p_reason, 1, 1000), p_status)
    returning req_id into l_id;
    p_ref := 'LV-' || to_char(l_id, 'FM00000');
    return null;
  end create_request;

  function get_balance (p_payload in clob) return clob is
    l_user varchar2(255) := user_of(json_object_t.parse(p_payload));
    l_b    json_object_t := json_object_t();
    l_res  json_object_t := json_object_t();
  begin
    ensure_user(l_user);
    for r in (select leave_type from fc_demo_leave_balances where app_user = l_user order by leave_type) loop
      l_b.put(r.leave_type, remaining(l_user, r.leave_type));
    end loop;
    l_res.put('user', l_user);
    l_res.put('year', to_number(to_char(sysdate, 'YYYY')));
    l_res.put('today', to_char(sysdate, 'YYYY-MM-DD'));
    l_res.put('remainingDays', l_b);
    return l_res.to_clob;
  end get_balance;

  function list_requests (p_payload in clob) return clob is
    l_user varchar2(255) := user_of(json_object_t.parse(p_payload));
    l_arr  json_array_t  := json_array_t();
    l_o    json_object_t;
    l_res  json_object_t := json_object_t();
  begin
    for r in (select req_id, leave_type, start_date, days, status, reason
                from fc_demo_leave_requests
               where app_user = l_user
               order by req_id desc
               fetch first 10 rows only) loop
      l_o := json_object_t();
      l_o.put('reference', 'LV-' || to_char(r.req_id, 'FM00000'));
      l_o.put('leaveType', r.leave_type);
      l_o.put('firstDay', to_char(r.start_date, 'YYYY-MM-DD'));
      l_o.put('days', r.days);
      l_o.put('status', r.status);
      l_o.put('reason', r.reason);
      l_arr.append(l_o);
    end loop;
    l_res.put('requests', l_arr);
    return l_res.to_clob;
  end list_requests;

  function book_leave (p_payload in clob) return clob is
    l_p    json_object_t := json_object_t.parse(p_payload);
    l_args json_object_t := l_p.get_object('args');
    l_res  json_object_t := json_object_t();
    l_ref  varchar2(20);
    l_err  varchar2(4000);
  begin
    l_err := create_request(user_of(l_p), lower(str_of(l_args, 'leave_type')), str_of(l_args, 'start_date'),
                            num_of(l_args, 'days'), str_of(l_args, 'reason'), 'BOOKED', l_ref);
    if l_err is not null then
      l_res.put('ok', false);
      l_res.put('error', l_err);
    else
      l_res.put('ok', true);
      l_res.put('reference', l_ref);
    end if;
    return l_res.to_clob;
  end book_leave;

  function submit_leave (p_payload in clob) return clob is
    l_p     json_object_t := json_object_t.parse(p_payload);
    l_slots json_object_t := l_p.get_object('slots');
    l_res   json_object_t := json_object_t();
    l_out   json_object_t := json_object_t();
    l_ref   varchar2(20);
    l_err   varchar2(4000);
  begin
    l_err := create_request(user_of(l_p), str_of(l_slots, 'leave_type'), str_of(l_slots, 'start_date'),
                            num_of(l_slots, 'days'), str_of(l_slots, 'reason'), 'SUBMITTED', l_ref);
    if l_err is not null then
      l_res.put('ok', false);
      l_res.put('message', l_err);
    else
      l_out.put('reference', l_ref);
      l_res.put('ok', true);
      l_res.put('slots', l_out);
    end if;
    return l_res.to_clob;
  end submit_leave;
end fc_demo_leave;
