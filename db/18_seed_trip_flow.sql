create or replace package fc_demo_trips authid definer as
  -- The fiscal year starts in this month (1 = January: FY26 is calendar 2026; 10 = October: FY26 runs
  -- Oct 2025 to Sep 2026). The label is the year the fiscal year ends in.
  c_fy_start_month constant pls_integer := 1;

  -- Where cancellation emails go when TRIP_APPROVERS has no row for the employee (null = no email).
  c_travel_desk_email constant varchar2(255) := null;

  -- The sender of the emails this package sends (trip approved). Use an address your mail server
  -- accepts; the flow's "notify_approver" Email step has its own From, so change both.
  c_mail_from constant varchar2(255) := 'travel-noreply@example.com';

  -- The approver of an employee's trips: TRIP_APPROVERS, else the travel desk (c_travel_desk_email).
  procedure approver_of (p_employee in varchar2, p_name out varchar2, p_email out varchar2);

  -- The employee's name and email for trip emails. By default: the APEX account's email
  -- (APEX_UTIL.GET_EMAIL), else the username itself when it is an email address (typical with
  -- single sign-on); null = no email. Replace with your HR lookup if you have one.
  procedure employee_of (p_employee in varchar2, p_name out varchar2, p_email out varchar2);

  -- 'FY26-1', 'FY26-2', ... numbered per fiscal year. Runs in the caller's transaction, so a failed
  -- save leaves no gap.
  function next_itinerary_no (p_date in date default sysdate) return varchar2;

  -- Lookup connector: {found, slots: {emergency_contacts: [...], editable_trips: n}} of the signed-in user.
  function get_profile (p_payload in clob) return clob;
  -- Lookup connector: loads the user's NEW, SAVED or REJECTED trip slots.edit_trip_id into the flow's
  -- fields; a rejected trip also returns rejection_note (the approver's reason).
  -- Only filled values are returned, so the flow asks just what's missing (e.g. a NEW draft).
  function load_trip (p_payload in clob) return clob;
  -- Submit connector: checks and saves the trip (status SAVED) and the user's emergency contacts.
  -- With slots.trip_id it updates that trip (only NEW, SAVED or REJECTED, only if nobody changed it since it was
  -- loaded); otherwise it creates one. Returns {ok, slots: {trip_id, itinerary_no, trip_status, trip_updated_at}, message}.
  function save_trip (p_payload in clob) return clob;
  -- Lookup connector: cancels the user's trip slots.cancel_trip_id (any status but CANCELLED, not yet
  -- started) with slots.cancel_reason, and withdraws a pending approval (APEX_WORKFLOW.TERMINATE).
  -- Returns {found, slots: {itinerary_no, cancel_note, trip_status}, message}. For a trip that was
  -- pending approval or approved it also returns approver_email, approver_name, trip_summary,
  -- previous_status and approval_task_note, which the flow's Email step sends to the approver.
  function cancel_trip (p_payload in clob) return clob;
  -- Lookup connector after the Workflow node: SAVED -> PENDING_APPROVAL, and keeps the workflow id.
  function mark_pending (p_payload in clob) return clob;

  -- For the TRIP_APPROVAL workflow's Invoke API activities, e.g. fc_demo_trips.set_status(:P_TRIP_ID, 'APPROVED').
  -- A cancelled trip is never changed, so an approval that arrives after a cancel has no effect.
  -- When a trip changes to APPROVED or REJECTED the employee is emailed (see employee_of). p_by, if
  -- given, is named as the approver; p_note is the approver's reason or comment, kept on a rejected trip
  -- and shown when the employee opens it again. E.g. set_status(:P_TRIP_ID, 'REJECTED', :APPROVER, :REASON).
  -- A failed email is logged with APEX_DEBUG and never undoes the decision.
  procedure set_status (p_trip_id in number, p_status in varchar2, p_by in varchar2 default null,
                        p_note in varchar2 default null);
end fc_demo_trips;
/

create or replace package body fc_demo_trips as

  function yn (p in varchar2) return varchar2 is
  begin
    return case when p in ('Y', 'N') then p end;
  end yn;

  function iso_date (p in varchar2) return date is
  begin
    return to_date(p, 'YYYY-MM-DD');
  end iso_date;

  -- The row version the chat carries between load and save (optimistic locking).
  function stamp (p in timestamp with time zone) return varchar2 is
  begin
    return to_char(p, 'YYYY-MM-DD"T"HH24:MI:SS.FF6TZH:TZM');
  end stamp;

  procedure put_if (p_obj in out nocopy json_object_t, p_key in varchar2, p_val in varchar2) is
  begin
    if p_val is not null then p_obj.put(p_key, p_val); end if;
  end put_if;

  function result (p_ok in boolean, p_message in varchar2, p_slots in json_object_t default null) return clob is
    l json_object_t := json_object_t();
  begin
    l.put('ok', p_ok);
    if p_message is not null then l.put('message', p_message); end if;
    if p_slots is not null then l.put('slots', p_slots); end if;
    return l.to_clob;
  end result;

  function next_itinerary_no (p_date in date default sysdate) return varchar2 is
    l_fy varchar2(4) := 'FY' || to_char(add_months(p_date, mod(13 - c_fy_start_month, 12)), 'YY');
    l_no number;
  begin
    -- The update locks the year's row, so two saves at once get different numbers.
    update trip_fy_counters set last_no = last_no + 1 where fiscal_year = l_fy returning last_no into l_no;
    if sql%rowcount = 0 then
      begin
        insert into trip_fy_counters (fiscal_year, last_no) values (l_fy, 1);
        l_no := 1;
      exception when dup_val_on_index then
        update trip_fy_counters set last_no = last_no + 1 where fiscal_year = l_fy returning last_no into l_no;
      end;
    end if;
    return l_fy || '-' || l_no;
  end next_itinerary_no;

  function get_profile (p_payload in clob) return clob is
    l_user  varchar2(255) := json_object_t.parse(p_payload).get_string('appUser');
    l_list  json_array_t  := json_array_t();
    l_c     json_object_t;
    l_slots json_object_t := json_object_t();
    l_res   json_object_t := json_object_t();
    l_n     number;
  begin
    for r in (select name, relationship, phone, email from trip_emergency_contacts where employee = l_user order by seq) loop
      l_c := json_object_t();
      l_c.put('name', r.name);
      l_c.put('relationship', r.relationship);
      l_c.put('phone', r.phone);
      if r.email is not null then l_c.put('email', r.email); end if;
      l_list.append(l_c);
    end loop;
    if l_list.get_size > 0 then l_slots.put('emergency_contacts', l_list); end if;
    select count(*) into l_n from trips where employee = l_user and status in ('NEW', 'SAVED', 'REJECTED');
    l_slots.put('editable_trips', l_n);
    select count(*) into l_n from trips t
     where t.employee = l_user and t.status <> 'CANCELLED'
       and not exists (select 1 from trip_destinations d where d.trip_id = t.trip_id and d.departure_date < trunc(sysdate));
    l_slots.put('cancellable_trips', l_n);
    l_res.put('found', true);
    l_res.put('slots', l_slots);
    return l_res.to_clob;
  end get_profile;

  function load_trip (p_payload in clob) return clob is
    l_p     json_object_t := json_object_t.parse(p_payload);
    l_user  varchar2(255) := l_p.get_string('appUser');
    l_id    number        := to_number(l_p.get_object('slots').get_string('edit_trip_id'));
    l_t     trips%rowtype;
    l_s     json_object_t := json_object_t();
    l_dest  json_array_t  := json_array_t();
    l_d     json_object_t;
    l_res   json_object_t := json_object_t();
  begin
    begin
      select * into l_t from trips where trip_id = l_id and employee = l_user and status in ('NEW', 'SAVED', 'REJECTED');
    exception when no_data_found then
      l_res.put('found', false);
      return l_res.to_clob;
    end;
    l_s.put('trip_id', l_t.trip_id);
    l_s.put('itinerary_no', l_t.itinerary_no);
    l_s.put('trip_status', l_t.status);
    l_s.put('trip_updated_at', stamp(l_t.updated_at));
    if l_t.status = 'REJECTED' then
      l_s.put('rejection_note', nvl(l_t.rejection_note, 'no reason given'));
    end if;
    put_if(l_s, 'travel_type', l_t.travel_type);
    put_if(l_s, 'business_purpose', l_t.business_purpose);
    for r in (select * from trip_destinations where trip_id = l_t.trip_id order by seq) loop
      l_d := json_object_t();
      l_d.put('city', r.city);
      l_d.put('country', r.country);
      l_d.put('departure_date', to_char(r.departure_date, 'YYYY-MM-DD'));
      l_d.put('arrival_date', to_char(r.arrival_date, 'YYYY-MM-DD'));
      l_d.put('travel_medium', r.travel_medium);
      l_d.put('transport_name', r.transport_name);
      l_dest.append(l_d);
    end loop;
    if l_dest.get_size > 0 then l_s.put('destinations', l_dest); end if;
    put_if(l_s, 'exp_devices', l_t.exp_devices);
    put_if(l_s, 'exp_device_list', l_t.exp_device_list);
    put_if(l_s, 'exp_tech_data', l_t.exp_tech_data);
    put_if(l_s, 'exp_sanctioned', l_t.exp_sanctioned);
    put_if(l_s, 'exp_foreign_officials', l_t.exp_foreign_officials);
    put_if(l_s, 'exp_hardware', l_t.exp_hardware);
    put_if(l_s, 'exp_encryption', l_t.exp_encryption);
    put_if(l_s, 'clr_passport', l_t.clr_passport);
    put_if(l_s, 'clr_visa', l_t.clr_visa);
    put_if(l_s, 'clr_briefing', l_t.clr_briefing);
    put_if(l_s, 'clr_level', l_t.clr_level);
    put_if(l_s, 'clr_fso_notified', l_t.clr_fso_notified);
    l_res.put('found', true);
    l_res.put('slots', l_s);
    return l_res.to_clob;
  end load_trip;

  function save_trip (p_payload in clob) return clob is
    l_p      json_object_t := json_object_t.parse(p_payload);
    l_user   varchar2(255) := l_p.get_string('appUser');          -- set by FC_ENGINE from the APEX session
    l_s      json_object_t := l_p.get_object('slots');
    l_dest   json_array_t  := case when l_s.has('destinations') and l_s.get('destinations').is_array then l_s.get_array('destinations') else json_array_t() end;
    l_cont   json_array_t  := case when l_s.has('emergency_contacts') and l_s.get('emergency_contacts').is_array then l_s.get_array('emergency_contacts') else json_array_t() end;
    l_type   varchar2(10)  := l_s.get_string('travel_type');
    l_d      json_object_t;
    l_dep    date;
    l_arr    date;
    l_id     number;
    l_no     varchar2(20);
    l_status trips.status%type;
    l_upd    trips.updated_at%type;
    l_out    json_object_t := json_object_t();
  begin
    -- The flow already asks for these; the server checks again because the rules live here.
    if l_dest.get_size = 0 then
      return result(false, 'Please add at least one destination: a trip can''t be saved without one.');
    end if;
    if l_cont.get_size = 0 then
      return result(false, 'Please add at least one emergency contact.');
    end if;
    if l_type is null or l_type not in ('PERSONAL', 'OFFICIAL', 'BOTH') then
      return result(false, 'Please choose the travel type.');
    end if;
    if l_type <> 'PERSONAL' and trim(l_s.get_string('business_purpose')) is null then
      return result(false, 'Official travel needs a business purpose.');
    end if;
    for i in 0 .. l_dest.get_size - 1 loop
      l_d   := treat(l_dest.get(i) as json_object_t);
      l_dep := iso_date(l_d.get_string('departure_date'));
      l_arr := iso_date(l_d.get_string('arrival_date'));
      if l_arr < l_dep then
        return result(false, 'Destination ' || (i + 1) || ' (' || l_d.get_string('city') || '): the arrival date is before the departure date. Tap Edit on Destinations, then Change on that destination to fix it.');
      end if;
    end loop;

    l_id := case when l_s.has('trip_id') then l_s.get_number('trip_id') end;
    if l_id is not null then
      -- Changing a trip: only the owner's NEW, SAVED or REJECTED trip, and only if nobody changed it since it was loaded.
      begin
        select status, updated_at, itinerary_no into l_status, l_upd, l_no
          from trips where trip_id = l_id and employee = l_user for update;
      exception when no_data_found then
        return result(false, 'That trip no longer exists.');
      end;
      if l_status not in ('NEW', 'SAVED', 'REJECTED') then
        return result(false, 'Trip ' || l_no || ' has already been sent for approval, so it can''t be changed here.');
      end if;
      if l_s.get_string('trip_updated_at') is null or stamp(l_upd) <> l_s.get_string('trip_updated_at') then
        return result(false, 'Trip ' || l_no || ' was changed somewhere else after you opened it. Please start again to load the latest version.');
      end if;
      update trips
         set travel_type = l_type,
             business_purpose = case when l_type <> 'PERSONAL' then l_s.get_string('business_purpose') end,
             status = 'SAVED',
             rejection_note = null,
             export_review = nvl(yn(l_s.get_string('export_review')), 'N'),
             exp_devices = yn(l_s.get_string('exp_devices')),
             exp_device_list = case when l_s.get_string('exp_devices') = 'Y' then l_s.get_string('exp_device_list') end,
             exp_tech_data = yn(l_s.get_string('exp_tech_data')),
             exp_sanctioned = yn(l_s.get_string('exp_sanctioned')),
             exp_foreign_officials = yn(l_s.get_string('exp_foreign_officials')),
             exp_hardware = yn(l_s.get_string('exp_hardware')),
             exp_encryption = yn(l_s.get_string('exp_encryption')),
             clr_passport = yn(l_s.get_string('clr_passport')),
             clr_visa = l_s.get_string('clr_visa'),
             clr_briefing = yn(l_s.get_string('clr_briefing')),
             clr_level = l_s.get_string('clr_level'),
             clr_fso_notified = case when l_s.get_string('clr_level') <> 'NONE' then yn(l_s.get_string('clr_fso_notified')) end,
             updated_at = systimestamp
       where trip_id = l_id;
      delete from trip_destinations where trip_id = l_id;
    else
      l_no := next_itinerary_no;
      insert into trips (itinerary_no, employee, travel_type, business_purpose, status, export_review,
                         exp_devices, exp_device_list, exp_tech_data, exp_sanctioned, exp_foreign_officials, exp_hardware, exp_encryption,
                         clr_passport, clr_visa, clr_briefing, clr_level, clr_fso_notified)
      values (l_no, l_user, l_type, case when l_type <> 'PERSONAL' then l_s.get_string('business_purpose') end, 'SAVED',
              nvl(yn(l_s.get_string('export_review')), 'N'),
              yn(l_s.get_string('exp_devices')), case when l_s.get_string('exp_devices') = 'Y' then l_s.get_string('exp_device_list') end,
              yn(l_s.get_string('exp_tech_data')), yn(l_s.get_string('exp_sanctioned')), yn(l_s.get_string('exp_foreign_officials')),
              yn(l_s.get_string('exp_hardware')), yn(l_s.get_string('exp_encryption')),
              yn(l_s.get_string('clr_passport')), l_s.get_string('clr_visa'), yn(l_s.get_string('clr_briefing')),
              l_s.get_string('clr_level'), case when l_s.get_string('clr_level') <> 'NONE' then yn(l_s.get_string('clr_fso_notified')) end)
      returning trip_id into l_id;
    end if;

    for i in 0 .. l_dest.get_size - 1 loop
      l_d := treat(l_dest.get(i) as json_object_t);
      insert into trip_destinations (trip_id, seq, city, country, departure_date, arrival_date, travel_medium, transport_name)
      values (l_id, i + 1, l_d.get_string('city'), l_d.get_string('country'),
              iso_date(l_d.get_string('departure_date')), iso_date(l_d.get_string('arrival_date')),
              l_d.get_string('travel_medium'), l_d.get_string('transport_name'));
    end loop;

    -- The contacts list in the chat is the whole list: replace the user's contacts with it.
    delete from trip_emergency_contacts where employee = l_user;
    for i in 0 .. l_cont.get_size - 1 loop
      l_d := treat(l_cont.get(i) as json_object_t);
      insert into trip_emergency_contacts (employee, seq, name, relationship, phone, email)
      values (l_user, i + 1, l_d.get_string('name'), l_d.get_string('relationship'), l_d.get_string('phone'), l_d.get_string('email'));
    end loop;

    l_out.put('trip_id', l_id);
    l_out.put('itinerary_no', l_no);
    l_out.put('trip_status', 'SAVED');
    select updated_at into l_upd from trips where trip_id = l_id;
    l_out.put('trip_updated_at', stamp(l_upd));
    return result(true, null, l_out);
  end save_trip;

  procedure approver_of (p_employee in varchar2, p_name out varchar2, p_email out varchar2) is
  begin
    select nvl(approver_name, approver_username), approver_email into p_name, p_email
      from trip_approvers where upper(employee) = upper(p_employee);
  exception when no_data_found then
    p_name  := 'Travel desk';
    p_email := c_travel_desk_email;
  end approver_of;

  procedure employee_of (p_employee in varchar2, p_name out varchar2, p_email out varchar2) is
  begin
    p_name := p_employee;
    begin
      p_email := apex_util.get_email(p_username => p_employee);
      p_name  := coalesce(apex_util.get_first_name(p_username => p_employee), p_employee);
    exception when others then
      p_email := null;   -- not an APEX account, or no workspace context
    end;
    if p_email is null and regexp_like(p_employee, '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$') then
      p_email := lower(p_employee);
    end if;
  end employee_of;

  -- "Berlin, Paris, 1 Mar 2027 to 5 Mar 2027 (official)"
  function trip_summary (p_trip_id in number, p_type in varchar2) return varchar2 is
    l varchar2(4000);
  begin
    select listagg(city, ', ') within group (order by seq) || ', '
           || to_char(min(departure_date), 'FMDD Mon YYYY') || ' to ' || to_char(max(arrival_date), 'FMDD Mon YYYY')
      into l
      from trip_destinations where trip_id = p_trip_id
    having count(*) > 0;
    return l || ' (' || lower(p_type) || ')';
  exception when no_data_found then
    return 'no destinations (' || lower(p_type) || ')';
  end trip_summary;

  function not_cancelled (p_message in varchar2) return clob is
    l json_object_t := json_object_t();
  begin
    l.put('found', false);
    l.put('message', p_message);
    return l.to_clob;
  end not_cancelled;

  function cancel_trip (p_payload in clob) return clob is
    l_p       json_object_t := json_object_t.parse(p_payload);
    l_user    varchar2(255) := l_p.get_string('appUser');
    l_s       json_object_t := l_p.get_object('slots');
    l_id      number        := to_number(l_s.get_string('cancel_trip_id'));
    l_reason  varchar2(400) := substr(trim(l_s.get_string('cancel_reason')), 1, 400);
    l_t       trips%rowtype;
    l_started number;
    l_note    varchar2(400);
    l_task    varchar2(400);
    l_aname   varchar2(200);
    l_amail   varchar2(255);
    l_out     json_object_t := json_object_t();
    l_res     json_object_t := json_object_t();
  begin
    begin
      select * into l_t from trips where trip_id = l_id and employee = l_user for update;
    exception when no_data_found then
      return not_cancelled('I couldn''t find that trip.');
    end;
    if l_t.status = 'CANCELLED' then
      return not_cancelled('Trip ' || l_t.itinerary_no || ' is already cancelled.');
    end if;
    select count(*) into l_started from trip_destinations where trip_id = l_id and departure_date < trunc(sysdate);
    if l_started > 0 then
      return not_cancelled('Trip ' || l_t.itinerary_no || ' has already started, so it can''t be cancelled here.');
    end if;

    update trips
       set status = 'CANCELLED', cancel_reason = l_reason, cancelled_at = systimestamp, updated_at = systimestamp
     where trip_id = l_id;

    -- TERMINATE only marks the workflow as terminated; the trip's own status is set above, and
    -- set_status ignores cancelled trips, so a late approval can't revive it.
    if l_t.status = 'PENDING_APPROVAL' and l_t.workflow_id is not null then
      savepoint fc_trip_wf;
      begin
        apex_workflow.terminate(p_instance_id => l_t.workflow_id);
        l_note := 'The approval request has been withdrawn.';
        l_task := 'The approval request has been withdrawn, so no action is needed.';
      exception when others then
        rollback to fc_trip_wf;
        apex_debug.error('Trip %s: workflow %s was not terminated: %s', l_t.itinerary_no, l_t.workflow_id, sqlerrm);
        l_note := 'The approval request could not be withdrawn automatically.';
        l_task := 'The approval task may still be open in your inbox: please reject it.';
      end;
    elsif l_t.status = 'PENDING_APPROVAL' then
      l_task := 'If an approval task for this trip is still open in your inbox, please reject it.';
    elsif l_t.status = 'APPROVED' then
      l_task := 'You had already approved this trip. Please release any bookings or budget held for it.';
    end if;

    -- Only a trip an approver has seen (pending or approved) gets an email to the approver.
    if l_t.status in ('PENDING_APPROVAL', 'APPROVED') then
      approver_of(l_user, l_aname, l_amail);
      if l_amail is not null then
        l_out.put('approver_email', l_amail);
        l_out.put('approver_name', l_aname);
        l_out.put('trip_summary', trip_summary(l_id, l_t.travel_type));
        l_out.put('previous_status', initcap(replace(l_t.status, '_', ' ')));
        l_out.put('approval_task_note', l_task);
      end if;
    end if;

    l_out.put('itinerary_no', l_t.itinerary_no);
    l_out.put('trip_status', 'CANCELLED');
    if l_note is not null then l_out.put('cancel_note', l_note); end if;
    l_res.put('found', true);
    l_res.put('slots', l_out);
    return l_res.to_clob;
  end cancel_trip;

  function mark_pending (p_payload in clob) return clob is
    l_p    json_object_t := json_object_t.parse(p_payload);
    l_s    json_object_t := l_p.get_object('slots');
    l_res  json_object_t := json_object_t();
    l_out  json_object_t := json_object_t();
    l_n    pls_integer;
  begin
    update trips
       set status = 'PENDING_APPROVAL', workflow_id = l_s.get_number('workflow_id'), updated_at = systimestamp
     where trip_id = l_s.get_number('trip_id')
       and employee = l_p.get_string('appUser')
       and status = 'SAVED';
    l_n := sql%rowcount;
    l_res.put('found', l_n = 1);
    if l_n = 1 then l_out.put('trip_status', 'PENDING_APPROVAL'); end if;
    l_res.put('slots', l_out);
    return l_res.to_clob;
  end mark_pending;

  -- "Your trip FY26-9 has been approved/rejected." to the employee. Queued by APEX_MAIL, sent after commit.
  procedure mail_decision (p_trip in trips%rowtype, p_status in varchar2, p_by in varchar2, p_note in varchar2) is
    l_name  varchar2(255);
    l_email varchar2(255);
    l_word  varchar2(20) := case p_status when 'APPROVED' then 'approved' else 'rejected' end;
    l_body  varchar2(4000);
  begin
    employee_of(p_trip.employee, l_name, l_email);
    if l_email is null then
      apex_debug.warn('Trip %s %s: no email address for %s', p_trip.itinerary_no, l_word, p_trip.employee);
      return;
    end if;
    l_body := 'Hello ' || l_name || ',' || chr(10) || chr(10)
           || 'Your trip ' || p_trip.itinerary_no || ' has been ' || l_word || '.' || chr(10) || chr(10)
           || 'Trip: ' || trip_summary(p_trip.trip_id, p_trip.travel_type) || chr(10)
           || case when p_by is not null then initcap(l_word) || ' by: ' || p_by || chr(10) end
           || case when p_note is not null then
                case p_status when 'APPROVED' then 'Comment: ' else 'Reason: ' end || p_note || chr(10) end
           || chr(10)
           || case p_status
                when 'APPROVED' then
                  'You can go ahead with your bookings. If your plans change, cancel the trip in the travel chat'
                  || ' so your approver is told.'
                else
                  'Please don''t make any bookings for this trip. To try again, open the travel chat, choose'
                  || ' "Change a saved trip", fix what''s needed and send it for approval again. If you no longer'
                  || ' need the trip, cancel it there.'
              end || chr(10);
    savepoint fc_trip_mail;
    begin
      apex_mail.send(
        p_to   => l_email,
        p_from => c_mail_from,
        p_subj => 'Trip ' || p_trip.itinerary_no || ' ' || l_word,
        p_body => l_body);
    exception when others then
      rollback to fc_trip_mail;
      apex_debug.error('Trip %s %s: email to %s failed: %s', p_trip.itinerary_no, l_word, l_email, sqlerrm);
    end;
  end mail_decision;

  procedure set_status (p_trip_id in number, p_status in varchar2, p_by in varchar2 default null,
                        p_note in varchar2 default null) is
    l_t trips%rowtype;
  begin
    begin
      select * into l_t from trips where trip_id = p_trip_id for update;
    exception when no_data_found then
      return;
    end;
    if l_t.status = 'CANCELLED' or l_t.status = p_status then
      return;
    end if;
    update trips
       set status = p_status,
           rejection_note = case when p_status = 'REJECTED' then substr(trim(p_note), 1, 1000) end,
           updated_at = systimestamp
     where trip_id = p_trip_id;
    if p_status in ('APPROVED', 'REJECTED') then
      mail_decision(l_t, p_status, p_by, substr(trim(p_note), 1, 1000));
    end if;
  end set_status;

