-- Trip booking sample: tables, the itinerary number (FY26-1, FY26-2, ...), three connectors and
-- the trip_booking flow. Safe to re-run: tables are created only if missing (Oracle 23ai or later),
-- the package is replaced, connectors are merged, and each run publishes a new flow version.
--
-- Statuses: NEW (the default for a trip created outside the chat, e.g. a draft on an APEX form),
-- SAVED (the chat saved it), PENDING_APPROVAL (sent to the TRIP_APPROVAL workflow), APPROVED (set by
-- that workflow through fc_demo_trips.set_status, which emails the employee), REJECTED (likewise, with
-- the approver's reason), CANCELLED (the employee cancelled it in the chat, which emails the approver).
-- NEW, SAVED and REJECTED trips can be changed in the chat ("Change a saved trip") and sent for approval
-- again; the itinerary number never
-- changes. Any trip that isn't cancelled and hasn't started yet can be cancelled ("Cancel a trip").
set define off

create table if not exists trip_fy_counters (
  fiscal_year  varchar2(4)  not null,
  last_no      number       default 0 not null,
  constraint trip_fy_counters_pk primary key (fiscal_year)
);

create table if not exists trips (
  trip_id                number generated by default on null as identity,
  itinerary_no           varchar2(20)   not null,
  employee               varchar2(255)  not null,
  travel_type            varchar2(10)   not null,
  business_purpose       varchar2(400),
  status                 varchar2(20)   default 'NEW' not null,
  export_review          varchar2(1)    default 'N' not null,
  exp_devices            varchar2(1),
  exp_device_list        varchar2(400),
  exp_tech_data          varchar2(1),
  exp_sanctioned         varchar2(1),
  exp_foreign_officials  varchar2(1),
  exp_hardware           varchar2(1),
  exp_encryption         varchar2(1),
  clr_passport           varchar2(1),
  clr_visa               varchar2(20),
  clr_briefing           varchar2(1),
  clr_level              varchar2(20),
  clr_fso_notified       varchar2(1),
  workflow_id            number,
  cancel_reason          varchar2(400),
  cancelled_at           timestamp with time zone,
  rejection_note         varchar2(1000),
  created_at             timestamp with time zone default systimestamp not null,
  updated_at             timestamp with time zone default systimestamp not null,
  constraint trips_pk primary key (trip_id),
  constraint trips_itinerary_uk unique (itinerary_no),
  constraint trips_type_ck check (travel_type in ('PERSONAL', 'OFFICIAL', 'BOTH')),
  constraint trips_status_ck check (status in ('NEW', 'SAVED', 'PENDING_APPROVAL', 'APPROVED', 'REJECTED', 'CANCELLED')),
  constraint trips_export_ck check (export_review in ('Y', 'N')),
  constraint trips_purpose_ck check (travel_type = 'PERSONAL' or business_purpose is not null)
);
create index if not exists trips_employee_ix on trips (employee, status);

