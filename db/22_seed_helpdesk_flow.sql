-- IT help desk sample (the Teams sample): table IT_TICKETS, three connectors, a lookup list and the
-- it_helpdesk flow. It suits a Teams channel: short questions, numbered choices, no personal data,
-- and fast connectors (Teams waits 5 seconds for each answer). It runs on APEX pages too.
-- Safe to re-run: the table is created only if missing (Oracle 23ai or later), the package is
-- replaced, connectors and the lookup list are merged, and each run publishes a new flow version.
--
-- To run it in Teams, install 20_fc_teams.sql and 21_fc_teams_ords.sql, then (see the README):
--   exec fc_teams.add_webhook('helpdesk', '<security token from Teams>', 'it_helpdesk');
--   exec fc_teams.map_user('<Entra object id>', '<APEX user>');
--   commit;
set define off

create table if not exists it_tickets (
  ticket_id   number generated by default on null as identity (start with 1001),
  ticket_no   varchar2(20)   generated always as ('IT-' || to_char(ticket_id)) virtual,
  reporter    varchar2(255)  not null,
  category    varchar2(20)   not null,
  title       varchar2(80)   not null,
  details     varchar2(1000),
  asset_tag   varchar2(20),
  impact      varchar2(10)   not null,
  urgency     varchar2(10)   not null,
  priority    varchar2(2)    not null,
  remote_ok   varchar2(1)    default 'N' not null,
  status      varchar2(10)   default 'OPEN' not null,
  close_note  varchar2(400),
  created_at  timestamp with time zone default systimestamp not null,
  closed_at   timestamp with time zone,
  constraint it_tickets_pk primary key (ticket_id),
  constraint it_tickets_no_uk unique (ticket_no),
  constraint it_tickets_cat_ck check (category in ('HARDWARE', 'SOFTWARE', 'NETWORK', 'ACCOUNT', 'PRINTER', 'OTHER')),
  constraint it_tickets_imp_ck check (impact in ('ME', 'TEAM', 'SITE')),
  constraint it_tickets_urg_ck check (urgency in ('LOW', 'NORMAL', 'HIGH')),
  constraint it_tickets_pri_ck check (priority in ('P1', 'P2', 'P3')),
  constraint it_tickets_rem_ck check (remote_ok in ('Y', 'N')),
  constraint it_tickets_st_ck check (status in ('OPEN', 'CLOSED'))
);
create index if not exists it_tickets_reporter_ix on it_tickets (reporter, status);

create or replace package fc_demo_helpdesk authid definer as
  -- Connectors (payload: {appUser, sessionId, slots: {...}}). Every one works on the signed-in
  -- user's own tickets only.
  -- it_my_tickets (lookup):   {found: true, slots: {open_tickets, ticket_list}}
  function my_tickets    (p_payload in clob) return clob;
  -- it_create_ticket (submit): slots category, title, details, asset_tag, impact, urgency, remote_ok
  --                            -> {ok: true, slots: {ticket_no, priority}} or {ok: false, message}
  function create_ticket (p_payload in clob) return clob;
  -- it_close_ticket (lookup): slots close_ticket_id, close_note -> {found, slots: {close_ticket_no}}
  function close_ticket  (p_payload in clob) return clob;
  -- P1 = everyone in the office and they can't work, P2 = either of those, P3 = the rest.
  function priority_of (p_impact in varchar2, p_urgency in varchar2) return varchar2;
end fc_demo_helpdesk;
/

create or replace package body fc_demo_helpdesk as

  function s (p_obj in json_object_t, p_key in varchar2) return varchar2 is
  begin
    if p_obj is null or not p_obj.has(p_key) or p_obj.get(p_key).is_null then return null; end if;
    if p_obj.get(p_key).is_string then return trim(p_obj.get_string(p_key)); end if;
    return trim(p_obj.get(p_key).to_string);
  end s;

  function priority_of (p_impact in varchar2, p_urgency in varchar2) return varchar2 is
  begin
    if p_impact = 'SITE' and p_urgency = 'HIGH' then return 'P1'; end if;
    if p_impact = 'SITE' or p_urgency = 'HIGH' then return 'P2'; end if;
    return 'P3';
  end priority_of;

  function my_tickets (p_payload in clob) return clob is
    l_user  varchar2(255) := json_object_t.parse(p_payload).get_string('appUser');
    l_list  varchar2(4000);
    l_n     number := 0;
    l_slots json_object_t := json_object_t();
    l_res   json_object_t := json_object_t();
  begin
    for r in (select ticket_no, title, priority from it_tickets
               where reporter = l_user and status = 'OPEN'
               order by created_at desc fetch first 20 rows only) loop
      l_n := l_n + 1;
      if nvl(lengthb(l_list), 0) < 3800 then
        l_list := l_list || case when l_n > 1 then chr(10) end || r.ticket_no || ' ' || r.title || ' (' || r.priority || ')';
      end if;
    end loop;
    select count(*) into l_n from it_tickets where reporter = l_user and status = 'OPEN';
    l_slots.put('open_tickets', l_n);
    l_slots.put('ticket_list', l_list);
    l_res.put('found', true);
    l_res.put('slots', l_slots);
    return l_res.to_clob;
  end my_tickets;

  function create_ticket (p_payload in clob) return clob is
    l_p     json_object_t := json_object_t.parse(p_payload);
    l_user  varchar2(255) := l_p.get_string('appUser');
    l_s     json_object_t := l_p.get_object('slots');
    -- read into variables first: a private function (s) can't be called inside SQL
    l_cat   varchar2(20)   := substr(s(l_s, 'category'), 1, 20);
    l_title varchar2(80)   := substr(s(l_s, 'title'), 1, 80);
    l_det   varchar2(1000) := substr(s(l_s, 'details'), 1, 1000);
    l_tag   varchar2(20)   := substr(upper(s(l_s, 'asset_tag')), 1, 20);
    l_imp   varchar2(10)   := substr(s(l_s, 'impact'), 1, 10);
    l_urg   varchar2(10)   := substr(s(l_s, 'urgency'), 1, 10);
    l_rem   varchar2(1)    := case when s(l_s, 'remote_ok') = 'Y' then 'Y' else 'N' end;
    l_pri   varchar2(2)    := priority_of(s(l_s, 'impact'), s(l_s, 'urgency'));
    l_no    varchar2(20);
    l_slots json_object_t := json_object_t();
    l_res   json_object_t := json_object_t();
  begin
    if l_user is null then
      l_res.put('ok', false);
      l_res.put('message', 'I don''t know who you are, so I can''t log a ticket. Please sign in and try again.');
      return l_res.to_clob;
    end if;
    insert into it_tickets (reporter, category, title, details, asset_tag, impact, urgency, priority, remote_ok)
    values (l_user, l_cat, l_title, l_det, case when l_cat = 'HARDWARE' then l_tag end,
            l_imp, l_urg, l_pri, l_rem)
    returning ticket_no into l_no;
    l_slots.put('ticket_no', l_no);
    l_slots.put('priority', l_pri);
    l_res.put('ok', true);
    l_res.put('slots', l_slots);
    return l_res.to_clob;
  exception when others then
    l_res := json_object_t();
    l_res.put('ok', false);
    l_res.put('message', 'Sorry, I couldn''t log the ticket. Please check the answers and try again.');
    return l_res.to_clob;
  end create_ticket;

  function close_ticket (p_payload in clob) return clob is
    l_p     json_object_t := json_object_t.parse(p_payload);
    l_user  varchar2(255) := l_p.get_string('appUser');
    l_s     json_object_t := l_p.get_object('slots');
    l_id    number;
    l_note  varchar2(400)  := substr(s(l_s, 'close_note'), 1, 400);   -- s can't be called inside SQL
    l_no    varchar2(20);
    l_slots json_object_t := json_object_t();
    l_res   json_object_t := json_object_t();
  begin
    begin
      l_id := to_number(s(l_s, 'close_ticket_id'));
    exception when value_error then
      l_id := null;
    end;
    update it_tickets
       set status = 'CLOSED', closed_at = systimestamp, close_note = l_note
     where ticket_id = l_id and reporter = l_user and status = 'OPEN'
    returning ticket_no into l_no;
    if sql%rowcount = 0 then
      l_res.put('found', false);
      return l_res.to_clob;
    end if;
    l_slots.put('close_ticket_no', l_no);
    l_res.put('found', true);
    l_res.put('slots', l_slots);
    return l_res.to_clob;
  end close_ticket;

end fc_demo_helpdesk;
/

merge into fc_connectors c
using (select 'it_my_tickets' id, 'fc_demo_helpdesk.my_tickets' tgt, 'IT help desk sample: counts and lists the signed-in user''s open tickets' dsc from dual
       union all select 'it_create_ticket', 'fc_demo_helpdesk.create_ticket', 'IT help desk sample: logs a ticket for the signed-in user (IT-nnnn) and sets its priority' from dual
       union all select 'it_close_ticket', 'fc_demo_helpdesk.close_ticket', 'IT help desk sample: closes one of the signed-in user''s open tickets' from dual) s
   on (c.connector_id = s.id)
 when matched then update set c.target = s.tgt, c.description = s.dsc, c.enabled = 'Y'
 when not matched then insert (connector_id, connector_type, target, description) values (s.id, 'PLSQL', s.tgt, s.dsc);
commit;

-- The signed-in user's open tickets (the "Which ticket is fixed?" choice).
merge into fc_lovs l
using (select 'it_my_open_tickets' id from dual) s
   on (l.lov_id = s.id)
 when matched then update set l.lov_type = 'SQL', l.query = q'~select ticket_id, ticket_no || ' - ' || title
  from it_tickets
 where reporter = :APP_USER and status = 'OPEN'
 order by created_at desc~', l.enabled = 'Y'
 when not matched then insert (lov_id, lov_type, query, description)
      values (s.id, 'SQL', q'~select ticket_id, ticket_no || ' - ' || title
  from it_tickets
 where reporter = :APP_USER and status = 'OPEN'
 order by created_at desc~', 'IT help desk sample: the signed-in user''s open tickets');
commit;


