// Generates a SQL script that publishes one or more flow JSON files through fc_engine.publish_flow.
//   node tools/build-seed.js flows/loan_application.json flows/update_application.json > db/07_seed_flows.sql
const fs = require('fs');
const files = process.argv.slice(2);
if (!files.length) { console.error('usage: node tools/build-seed.js <flow.json> [more.json ...]'); process.exit(1); }

function block(file) {
  const def = JSON.parse(fs.readFileSync(file, 'utf8'));   // validates JSON
  const json = JSON.stringify(def, null, 2);
  if (json.includes("~'")) throw new Error(file + " contains the q-quote terminator ~'");
  // Split into <= 4000-char pieces so no single literal hits SQL*Plus / PL/SQL limits.
  const chunks = json.match(/[\s\S]{1,4000}/g);
  return `-- ${file.replace(/\\/g, '/')}
declare
  l_def     clob;
  l_version number;
begin
  dbms_lob.createtemporary(l_def, true);
${chunks.map((c) => `  dbms_lob.append(l_def, q'~${c}~');`).join('\n')}
  l_version := fc_engine.publish_flow(l_def);
  dbms_output.put_line('Published ${def.flowId} version ' || l_version);
  commit;
end;
/
`;
}

process.stdout.write('-- Generated by tools/build-seed.js. Do not edit by hand.\nset define off\n\n' + files.map(block).join('\n'));
